    finalRarityKey === 'jackpot' ? (evolved ? '\n✨ Evolved Jackpot — the fixed 200,000,000 XP payout is unchanged.' : '') : luck.buildEvolvedCommandExtra(
        evolved,
        "ROLL"
    );


