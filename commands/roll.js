function getRollCountdownEndsAt(
    rollAccess,
    remainingMs
){

    const now =
        Date.now();


    const explicitRemaining =
        Number(
            remainingMs
        );


    const storedRemaining =
        Number(
            rollAccess?.cooldownEndsAt
        ) - now;


    const hasStoredDeadline =
        Number.isFinite(
            Number(
                rollAccess?.cooldownEndsAt
            )
        )
        &&
        Number(
            rollAccess?.cooldownEndsAt
        ) > 0;


    const requestedRemaining =
        Number.isFinite(explicitRemaining)
        &&
        explicitRemaining >= 0
            ? explicitRemaining
            : (
                hasStoredDeadline
                    ? Math.max(
                        0,
                        storedRemaining
                    )
                    : ROLL_COOLDOWN_MS
            );


    const safeRemaining =
        Math.max(
            0,
            Math.min(
                ROLL_COOLDOWN_MS,
                requestedRemaining
            )
        );


    return (
        now +
        safeRemaining
    );

}


function isPermanentRollEditError(error){

    const code =
        Number(
            error?.code
            ??
            error?.rawError?.code
            ??
            error?.data?.code
        );


    const status =
        Number(
            error?.status
            ??
            error?.statusCode
        );


    return (
        PERMANENT_ROLL_EDIT_ERROR_CODES.has(
            code
        )
        ||
        status === 403
        ||
        status === 404
    );

}


function getRollCountdownScheduleDelay(
    cooldownEndsAt,
    now = Date.now()
){

    const remaining =
        Number(cooldownEndsAt) -
        Number(now);


    if(
        !Number.isFinite(remaining)
        ||
        remaining <= 0
    ){

        return 0;

    }


    const seconds =
        Math.ceil(
            remaining / 1000
        );


    const untilNextSecond =
        remaining -
        (
            seconds - 1
        ) * 1000;


    // Run just after the next displayed-second boundary. Every later delay is
    // recalculated from the absolute deadline, so lag makes the display jump
    // to the correct number instead of permanently slowing the countdown.
    return Math.max(
        25,
        Math.min(
            1100,
            Math.ceil(
                untilNextSecond
            ) + 25
        )
    );

}


function startRollMessageCountdown(
    sentMessage,
    originalContent,
    cooldownEndsAt
){

    if(
        !sentMessage
        ||
        typeof sentMessage.edit !== "function"
        ||
        !ROLL_COUNTDOWN_PATTERN.test(
            String(
                originalContent
            )
        )
    ){

        return null;

    }


    let lastRenderedState =
        getDisplayedCooldownSeconds(
            cooldownEndsAt -
            Date.now()
        );


    let timer =
        null;


    let stopped =
        false;


    const stop = () => {

        stopped =
            true;


        if(timer){

            clearTimeout(
                timer
            );

            timer =
                null;

        }

    };


    let update;


    const schedule = delay => {

        if(stopped){
            return;
        }


        if(timer){

            clearTimeout(
                timer
            );

        }


        timer =
            setTimeout(
                update,
                Math.max(
                    0,
                    Number(delay) || 0
                )
            );


        if(
            typeof timer.unref ===
            "function"
        ){

            timer.unref();

        }

    };


    update = async() => {

        timer =
            null;


        if(stopped){
            return;
        }


        const now =
            Date.now();


        const seconds =
            getDisplayedCooldownSeconds(
                cooldownEndsAt -
                now
            );


        const ready =
            seconds <= 0;


        const nextState =
            ready
                ? "ready"
                : seconds;


        if(nextState === lastRenderedState){

            schedule(
                getRollCountdownScheduleDelay(
                    cooldownEndsAt,
                    now
                )
            );

            return;

        }


        try{

            await sentMessage.edit({
                content:
                    ready
                        ? replaceRollCountdownWithReady(
                            originalContent
                        )
                        : replaceRollCountdown(
                            originalContent,
                            seconds
                        ),
                allowedMentions: {
                    parse: []
                }
            });


            lastRenderedState =
                nextState;


            if(ready){

                stop();
                return;

            }

        }
        catch(error){

            if(
                isPermanentRollEditError(
                    error
                )
                ||
                Date.now() >
                    cooldownEndsAt +
                    ROLL_FINAL_EDIT_RETRY_WINDOW_MS
            ){

                stop();
                return;

            }


            // Rate limits, temporary Discord failures, and network hiccups
            // retry instead of permanently freezing the countdown.
            schedule(
                ROLL_EDIT_RETRY_DELAY_MS
            );

            return;
        }


        schedule(
            getRollCountdownScheduleDelay(
                cooldownEndsAt
            )
        );

    };


    schedule(
        getRollCountdownScheduleDelay(
            cooldownEndsAt
        )
    );


    return {
        stop
    };

}


async function sendMessageWithRollCountdown(
    sendMessage,
    content,
    rollAccess,
    remainingMs
){

    const cooldownEndsAt =
        getRollCountdownEndsAt(
            rollAccess,
            remainingMs
        );


    const seconds =
        getDisplayedCooldownSeconds(
            cooldownEndsAt -
            Date.now()
        );


    const initialContent =
        seconds <= 0
            ? replaceRollCountdownWithReady(
                content
            )
            : replaceRollCountdown(
                content,
                seconds
            );


    const sentMessage =
        await sendMessage(
            initialContent
        );


    startRollMessageCountdown(
        sentMessage,
        initialContent,
        cooldownEndsAt
    );


    return sentMessage;

}


