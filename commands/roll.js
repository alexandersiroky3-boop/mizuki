function getDisplayedCooldownSeconds(
    remainingMs
){

    const remaining =
        Number(
            remainingMs
        );


    if(
        !Number.isFinite(remaining)
        ||
        remaining <= 0
    ){

        return 0;

    }


    return Math.min(
        ROLL_SETTINGS.cooldownSeconds,
        Math.max(
            1,
            Math.ceil(
                remaining / 1000
            )
        )
    );

}


function buildRollCountdownLine(
    seconds
){

    const safeSeconds =
        Math.max(
            0,
            Math.min(
                ROLL_SETTINGS.cooldownSeconds,
                Math.floor(
                    Number(
                        seconds
                    ) || 0
                )
            )
        );


    const secondLabel =
        safeSeconds === 1
            ? "second"
            : "seconds";


    return (
        ROLL_CLOCK_EMOJI +
        " **Try again in " +
        safeSeconds +
        " " +
        secondLabel +
        "...**"
    );

}


