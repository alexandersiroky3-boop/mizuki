async function playRollReveal(
    message,
    rolledXP,
    wait = waitForRollReveal
){

    const emojiSequence =
        getRollRevealEmojiSequence(
            rolledXP,
            message.guild
        );


    if(emojiSequence.length === 0){
        return null;
    }


    const waitFunction =
        typeof wait === "function"
            ? wait
            : waitForRollReveal;

    let revealMessage = null;


    try{

        revealMessage =
            await message.reply({
                content:
                    buildRollRevealText(
                        emojiSequence[0],
                        3
                    ),

                allowedMentions: {
                    repliedUser: false,
                    parse: []
                }
            });


        if(
            !revealMessage
            ||
            typeof revealMessage.edit !==
                "function"
        ){

            return revealMessage;

        }


        for(
            let emojiIndex = 0;
            emojiIndex < emojiSequence.length;
            emojiIndex++
        ){

            const emoji =
                emojiSequence[emojiIndex];


            if(emojiIndex > 0){

                await revealMessage.edit({
                    content:
                        buildRollRevealText(
                            emoji,
                            3
                        ),
                    allowedMentions: {
                        parse: []
                    }
                });

            }


            await waitFunction(
                ROLL_REVEAL_FRAME_DELAY_MS
            );


            for(
                let dotCount = 1;
                dotCount <= 3;
                dotCount++
            ){

                await revealMessage.edit({
                    content:
                        buildRollRevealText(
                            emoji,
                            dotCount
                        ),
                    allowedMentions: {
                        parse: []
                    }
                });


                await waitFunction(
                    ROLL_REVEAL_FRAME_DELAY_MS
                );

            }

        }

    }
    catch(_error){

        // A missing permission, a deleted loading message, or a temporary
        // Discord edit failure must never prevent the real roll result.

    }
    finally{

        if(
            revealMessage
            &&
            typeof revealMessage.delete ===
                "function"
        ){

            try{
                await revealMessage.delete();
            }
            catch(_error){
                // The final roll result still needs to be sent.
            }

        }

    }


    return revealMessage;

}


function splitLongMessage(
    content,
    maxLength = ROLL_MESSAGE_MAX_LENGTH
){

    const paragraphs =
        String(content || "")
            .split("\n\n");

    const chunks = [];
    let chunk = "";


    function pushPiece(piece){

        const candidate =
            chunk
                ? `${chunk}\n\n${piece}`
                : piece;


        if(candidate.length <= maxLength){
            chunk = candidate;
            return;
        }


        if(chunk){
            chunks.push(chunk);
            chunk = "";
        }


        if(piece.length <= maxLength){
            chunk = piece;
            return;
        }


        for(
            let start = 0;
            start < piece.length;
            start += maxLength
        ){

            const slice =
                piece.slice(
                    start,
                    start + maxLength
                );


            if(slice.length === maxLength){
                chunks.push(slice);
            }
            else{
                chunk = slice;
            }

        }

    }


    for(const paragraph of paragraphs){
        pushPiece(paragraph);
    }


    if(chunk){
        chunks.push(chunk);
    }


    return chunks;

}


async function sendRollResultMessage(
    message,
    rollAccess,
    content
){

    const cooldownEndsAt =
        getRollCountdownEndsAt(
            rollAccess
        );

    const seconds =
        getDisplayedCooldownSeconds(
            cooldownEndsAt -
            Date.now()
        );

    const preparedContent =
        seconds <= 0
            ? replaceRollCountdownWithReady(
                content
            )
            : replaceRollCountdown(
                content,
                seconds
            );

    const chunks =
        splitLongMessage(
            preparedContent
        );

    let lastSentMessage = null;


    for(
        let index = 0;
        index < chunks.length;
        index++
    ){

        const chunk =
            chunks[index];


        lastSentMessage =
            await message.channel.send({
                content: chunk,

                allowedMentions: {
                    users:
                        index === 0
                            ? [message.author.id]
                            : [],
                    roles: [],
                    repliedUser: false
                }
            });


        if(
            ROLL_COUNTDOWN_PATTERN.test(
                chunk
            )
        ){

            startRollMessageCountdown(
                lastSentMessage,
                chunk,
                cooldownEndsAt
            );

        }

    }


    return lastSentMessage;

}


function getRollBonusPercentRange(
    rolledXP
){

    const safeXP =
        Number(rolledXP) || 0;


    if(safeXP >= 100000000){
        return {
            minimumPercentLess: 5,
            maximumPercentLess: 10
        };
    }


    if(safeXP > 5000000){
        return {
            minimumPercentLess: 15,
            maximumPercentLess: 50
        };
    }


    if(safeXP > 500000){
        return {
            minimumPercentLess: 15,
            maximumPercentLess: 50
        };
    }


    if(safeXP > 100000){
        return {
            minimumPercentLess: 10,
            maximumPercentLess: 30
        };
    }


    if(safeXP > 25000){
        return {
            minimumPercentLess: 15,
            maximumPercentLess: 50
        };
    }


    return null;

}


function rollPercentageLessBonus(
    rolledXP,
    minimumPercentLess,
    maximumPercentLess,
    random = Math.random
){

    const safeXP =
        Math.max(
            0,
            Math.floor(
                Number(rolledXP) || 0
            )
        );

    const safeMinimumPercentLess =
        Math.max(
            0,
            Math.min(
                100,
                Number(minimumPercentLess) || 0
            )
        );

    const safeMaximumPercentLess =
        Math.max(
            safeMinimumPercentLess,
            Math.min(
                100,
                Number(maximumPercentLess) || 0
            )
        );

    const minimumBonus =
        Math.floor(
            safeXP *
            (
                100 -
                safeMaximumPercentLess
            ) /
            100
        );

    const maximumBonus =
        Math.floor(
            safeXP *
            (
                100 -
                safeMinimumPercentLess
            ) /
            100
        );


    if(maximumBonus <= minimumBonus){
        return minimumBonus;
    }


    const position =
        Math.max(
            0,
            Math.min(
                0.999999999999,
                Number(random()) || 0
            )
        );


    return (
        minimumBonus +
        Math.floor(
            position *
            (
                maximumBonus -
                minimumBonus +
                1
            )
        )
    );

}


