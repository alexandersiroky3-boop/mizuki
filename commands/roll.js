    buildRollCooldownExtra(
        rollAccess
    );


const rollGuaranteeFooter =
    buildRollGuaranteeFooter(
        forcedNegativeByTroll
            ? {
                ...rollGuarantee,
                guaranteed: false
            }
            : rollGuarantee
    );


