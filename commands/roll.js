    luck.buildRollExtras(
        message,
        usedLuckBoost,
        wonLuckBoost
    )
    + xpBoostDropExtra
    + guaranteedRollExtra
    + megaRollExtra
    + rollingUpgradeExtra
    + evolvedExtra
    + chestDropExtra;


